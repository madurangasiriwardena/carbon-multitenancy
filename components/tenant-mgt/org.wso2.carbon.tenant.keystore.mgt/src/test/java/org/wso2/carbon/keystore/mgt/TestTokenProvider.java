package org.wso2.carbon.keystore.mgt;

import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.security.InvalidAlgorithmParameterException;
import java.security.InvalidKeyException;
import java.security.InvalidParameterException;
import java.security.Key;
import java.security.KeyPair;
import java.security.KeyPairGenerator;
import java.security.KeyPairGeneratorSpi;
import java.security.KeyStore;
import java.security.KeyStoreException;
import java.security.KeyStoreSpi;
import java.security.PrivateKey;
import java.security.Provider;
import java.security.PublicKey;
import java.security.SecureRandom;
import java.security.Signature;
import java.security.SignatureException;
import java.security.SignatureSpi;
import java.security.UnrecoverableKeyException;
import java.security.cert.Certificate;
import java.security.spec.AlgorithmParameterSpec;
import java.util.Arrays;
import java.util.Date;
import java.util.Enumeration;
import java.util.List;
import java.util.concurrent.CopyOnWriteArrayList;
import java.util.concurrent.atomic.AtomicInteger;

/**
 * Test JCA provider that simulates a PKCS#11 token: a "PKCS11" key store (like SunPKCS11, the first load(null, pin)
 * logs in and later loads accept any PIN; key passwords are ignored; entries are stored immediately), an RSA key pair generator and RSA signatures. It records the private keys
 * it generated and counts the signatures it made, so tests can check that key generation and certificate signing
 * happened through the token provider.
 */
public class TestTokenProvider extends Provider {

    private static final long serialVersionUID = 1L;
    private static final char[] ENTRY_PASSWORD = "entry".toCharArray();
    private static final String[] SIGNATURE_ALGORITHMS =
            {"SHA256withRSA", "SHA384withRSA", "SHA512withRSA", "SHA1withRSA", "MD5withRSA"};

    private final char[] pin;
    private volatile boolean loggedIn;
    private final transient KeyStore token;
    private final transient List<PrivateKey> generatedKeys = new CopyOnWriteArrayList<>();
    private final transient AtomicInteger signatures = new AtomicInteger();

    public TestTokenProvider(String name, char[] pin) throws Exception {

        super(name, "1.0", "Simulated PKCS#11 token for tests");
        this.pin = pin.clone();
        token = KeyStore.getInstance("PKCS12");
        token.load(null, ENTRY_PASSWORD);
        TestTokenProvider self = this;
        putService(new Service(this, "KeyStore", "PKCS11", TokenKeyStoreSpi.class.getName(), null, null) {
            @Override
            public Object newInstance(Object constructorParameter) {

                return new TokenKeyStoreSpi(self);
            }
        });
        putService(new Service(this, "KeyPairGenerator", "RSA", TokenKeyPairGeneratorSpi.class.getName(), null,
                null) {
            @Override
            public Object newInstance(Object constructorParameter) {

                return new TokenKeyPairGeneratorSpi(self);
            }
        });
        for (String algorithm : SIGNATURE_ALGORITHMS) {
            putService(new Service(this, "Signature", algorithm, TokenSignatureSpi.class.getName(), null, null) {
                @Override
                public Object newInstance(Object constructorParameter) {

                    return new TokenSignatureSpi(self, getAlgorithm());
                }
            });
        }
    }

    public KeyStore getToken() {

        return token;
    }

    /**
     * @return True if the key equals (same key material) a private key generated by this token.
     */
    public boolean isGeneratedKey(Key key) {

        return key != null && generatedKeys.stream().anyMatch(key::equals);
    }

    public int getSignatureCount() {

        return signatures.get();
    }

    private static final class TokenKeyPairGeneratorSpi extends KeyPairGeneratorSpi {

        private final TestTokenProvider provider;
        private final KeyPairGenerator delegate;

        TokenKeyPairGeneratorSpi(TestTokenProvider provider) {

            this.provider = provider;
            try {
                delegate = KeyPairGenerator.getInstance("RSA", "SunRsaSign");
            } catch (Exception e) {
                throw new IllegalStateException(e);
            }
        }

        @Override
        public void initialize(int keySize, SecureRandom random) {

            delegate.initialize(keySize, random);
        }

        @Override
        public KeyPair generateKeyPair() {

            KeyPair keyPair = delegate.generateKeyPair();
            provider.generatedKeys.add(keyPair.getPrivate());
            return keyPair;
        }
    }

    private static final class TokenSignatureSpi extends SignatureSpi {

        private final TestTokenProvider provider;
        private final Signature delegate;

        TokenSignatureSpi(TestTokenProvider provider, String algorithm) {

            this.provider = provider;
            try {
                delegate = Signature.getInstance(algorithm, "SunRsaSign");
            } catch (Exception e) {
                throw new IllegalStateException(e);
            }
        }

        @Override
        protected void engineInitSign(PrivateKey privateKey) throws InvalidKeyException {

            if (!provider.isGeneratedKey(privateKey)) {
                throw new InvalidKeyException("Only keys generated in this token are supported.");
            }
            delegate.initSign(privateKey);
        }

        @Override
        protected void engineInitVerify(PublicKey publicKey) throws InvalidKeyException {

            delegate.initVerify(publicKey);
        }

        @Override
        protected void engineSetParameter(AlgorithmParameterSpec params) throws InvalidAlgorithmParameterException {

            delegate.setParameter(params);
        }

        @Override
        protected void engineUpdate(byte b) throws SignatureException {

            delegate.update(b);
        }

        @Override
        protected void engineUpdate(byte[] bytes, int off, int len) throws SignatureException {

            delegate.update(bytes, off, len);
        }

        @Override
        protected byte[] engineSign() throws SignatureException {

            provider.signatures.incrementAndGet();
            return delegate.sign();
        }

        @Override
        protected boolean engineVerify(byte[] sigBytes) throws SignatureException {

            return delegate.verify(sigBytes);
        }

        @Override
        @Deprecated
        protected void engineSetParameter(String param, Object value) {

            throw new InvalidParameterException("Not supported.");
        }

        @Override
        @Deprecated
        protected Object engineGetParameter(String param) {

            throw new InvalidParameterException("Not supported.");
        }
    }

    private static final class TokenKeyStoreSpi extends KeyStoreSpi {

        private final TestTokenProvider provider;

        TokenKeyStoreSpi(TestTokenProvider provider) {

            this.provider = provider;
        }

        private KeyStore token() {

            return provider.token;
        }

        @Override
        public Key engineGetKey(String alias, char[] password) throws UnrecoverableKeyException {

            try {
                return token().getKey(alias, ENTRY_PASSWORD);
            } catch (Exception e) {
                throw new IllegalStateException(e);
            }
        }

        @Override
        public Certificate[] engineGetCertificateChain(String alias) {

            try {
                return token().getCertificateChain(alias);
            } catch (KeyStoreException e) {
                throw new IllegalStateException(e);
            }
        }

        @Override
        public Certificate engineGetCertificate(String alias) {

            try {
                return token().getCertificate(alias);
            } catch (KeyStoreException e) {
                throw new IllegalStateException(e);
            }
        }

        @Override
        public Date engineGetCreationDate(String alias) {

            try {
                return token().getCreationDate(alias);
            } catch (KeyStoreException e) {
                throw new IllegalStateException(e);
            }
        }

        @Override
        public void engineSetKeyEntry(String alias, Key key, char[] password, Certificate[] chain)
                throws KeyStoreException {

            token().setKeyEntry(alias, key, ENTRY_PASSWORD, chain);
        }

        @Override
        public void engineSetKeyEntry(String alias, byte[] key, Certificate[] chain) throws KeyStoreException {

            throw new KeyStoreException("Not supported.");
        }

        @Override
        public void engineSetCertificateEntry(String alias, Certificate cert) throws KeyStoreException {

            token().setCertificateEntry(alias, cert);
        }

        @Override
        public void engineDeleteEntry(String alias) throws KeyStoreException {

            token().deleteEntry(alias);
        }

        @Override
        public Enumeration<String> engineAliases() {

            try {
                return token().aliases();
            } catch (KeyStoreException e) {
                throw new IllegalStateException(e);
            }
        }

        @Override
        public boolean engineContainsAlias(String alias) {

            try {
                return token().containsAlias(alias);
            } catch (KeyStoreException e) {
                throw new IllegalStateException(e);
            }
        }

        @Override
        public int engineSize() {

            try {
                return token().size();
            } catch (KeyStoreException e) {
                throw new IllegalStateException(e);
            }
        }

        @Override
        public boolean engineIsKeyEntry(String alias) {

            try {
                return token().isKeyEntry(alias);
            } catch (KeyStoreException e) {
                throw new IllegalStateException(e);
            }
        }

        @Override
        public boolean engineIsCertificateEntry(String alias) {

            try {
                return token().isCertificateEntry(alias);
            } catch (KeyStoreException e) {
                throw new IllegalStateException(e);
            }
        }

        @Override
        public String engineGetCertificateAlias(Certificate cert) {

            try {
                return token().getCertificateAlias(cert);
            } catch (KeyStoreException e) {
                throw new IllegalStateException(e);
            }
        }

        @Override
        public void engineStore(OutputStream stream, char[] password) {

            // Entries are stored in the token immediately.
        }

        @Override
        public void engineLoad(InputStream stream, char[] password) throws IOException {

            // Like SunPKCS11, the PIN is checked only when the token is not logged in yet.
            if (provider.loggedIn) {
                return;
            }
            if (password == null || !Arrays.equals(password, provider.pin)) {
                throw new IOException("Token login failed: wrong PIN.");
            }
            provider.loggedIn = true;
        }
    }
}
